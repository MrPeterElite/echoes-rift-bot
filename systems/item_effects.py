FOOD_DURATION = 30 * 60
FOOD_CAP = 30
BASIC_HEAL_LIMIT = 20


def describe_effect(item):
    effect = item.get('effect', {})
    kind = effect.get('type')
    if kind == 'food_hp':
        return (f"🍽 +{effect['amount']} временных HP на {FOOD_DURATION // 60} минут.\n"
                "Если сцена началась до истечения срока — запас действует до её конца.\n"
                f"Бонусы не складываются, максимум +{FOOD_CAP} HP. Более сильный заменяет слабый.\n"
                "Только вне боя. Основное здоровье и броню не восстанавливает.")
    if kind == 'heal':
        limit = ("Общий лимит бинтов и гемостатиков: " + str(BASIC_HEAL_LIMIT) +
                 " HP на эпизод ранения, включая бой и помощь после него. "
                 "Сбрасывается после полного восстановления вне боя."
                 if effect['group'] == 'basic' else
                 "В боевой сцене — один медкомплект на получателя.")
        return (f"❤️ Восстанавливает до {effect['amount']} основного HP, не выше максимума.\n"
                f"{limit}\nПри 0 HP обычное лечение недоступно. Броню и запас еды не восстанавливает.\n"
                "В бою применение занимает основное действие — пока его учитывает ведущий.\n"
                "Остановка кровотечения появится вместе с механикой ранений.")
    if item.get('category') in ('food', 'medicine'):
        return "🎭 Пока используется только для RP: без лечения, усилений и реанимации. Одна единица расходуется."
    return ''
